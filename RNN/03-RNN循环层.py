import torch  # 导入PyTorch深度学习框架
import torch.nn as nn  # 导入PyTorch神经网络模块

if __name__ == '__main__':  # 程序入口判断，确保只在直接运行脚本时执行
    # 创建RNN循环层
    """
        input_size：词向量的维度。也就是一个单词要用多少个数字表示 128
        hidden_size：隐藏状态的向量维度数，也就是一行中有多少个数字。表示有多少个特征个数
        num_layers：隐藏层的层数，默认是1
    """
    # 创建RNN循环神经网络层实例
    rnn = nn.RNN(input_size=128, hidden_size=256, num_layers=1)

    # 输入数据得到预测结果
    """
        输入层数据各个数字含义表示：
            第一个数字：句子的长度,这里的句子长度是5指的是每个输入句子（或者序列）包含5个token，是序列数据在时间/顺序维度上的长度。
            第二个数字：批次的大小，一次处理多少条数据，表示一次性输入模型的样本数量为32个（同时处理32个句子）
            第三个数字：一个词用多少个数字的向量表示。需要与前面的RNN中input_size参数保持一致，每个token被转换为一个128维的向量（通常是词嵌入向量）
    """
    # 创建随机输入数据张量，形状为(句子长度5, 批次大小32, 词向量维度128)
    inputs = torch.randn(5, 32, 128)
    print(f"输入层数据{inputs}")

    """
        输入层隐藏状态各个数字含义表示：
            第一个数字：隐藏层的层数。需要与前面的RNN中num_layers参数保持一致
            第二个数字：批次的大小，一次处理多少条数据。需要与输入层数据的批次大小保持一致
            第三个数字：隐藏状态用多少个数字的向量表示。需要与前面的RNN中hidden_size参数保持一致
    """
    # 创建初始隐藏状态张量，形状为(层数1, 批次大小32, 隐藏状态维度256)
    hidden = torch.zeros(1, 32, 256)

    """
        输入【inputs本次的输入数据】、【hidden上一次的隐藏状态】
            输入给到RNN循环神经网络层
        输出【output本次循环的预测结果】、【new_hidden本次循环的隐藏状态】
    """
    # 将输入数据和隐藏状态传入RNN层，得到输出和新的隐藏状态
    output, new_hidden = rnn(inputs, hidden)
    # 打印本次循环的预测结果形状
    print(f"本次循环的预测结果{output.shape}")
    # 打印本次循环的隐藏状态形状
    print(f"本次循环的隐藏状态{new_hidden.shape}")

    # 打印预测结果的具体数值
    print(output)
    # 打印隐藏状态的具体数值
    print(new_hidden)
