import torch

if __name__ == '__main__':
    # 1- 初始化待优化变量x（可理解为单特征的权重）
    """
    初始化关键说明：
    - requires_grad=True：标记x需要计算梯度，启用PyTorch自动微分功能（核心参数）
    - dtype=torch.float32：必须使用浮点类型，因为梯度计算（如x_new = x_old - lr*grad）会产生小数，整数无法保存梯度信息
    - 初始值设为10.0：我们的目标是通过梯度下降找到使损失函数最小的x值
    """
    x = torch.tensor(10, requires_grad=True, dtype=torch.float32)
    print(f"初始变量x：{x}（需要优化的初始值）\n")

    # 2- 多轮次梯度下降优化（通过多次迭代逐步逼近最优解）
    """
    为什么需要多轮迭代？
    单次梯度更新只能让x向最优方向迈一小步（受学习率lr限制），多次迭代才能逐渐接近最优值。
    此处设置100轮（epochs=100），通过循环实现多轮更新。
    """
    epochs = 100  # 迭代总轮次
    for epoch in range(epochs):
        # 2.1- 定义损失函数y（目标：找到使y最小的x值）
        """
        损失函数公式：y = x² + 20
        数学分析：这是一个二次函数，开口向上，最小值在导数为0的点。
        求导得：dy/dx = 2x，令导数为0，得x=0时y取得最小值20（此时y=0²+20=20）。
        因此，我们的优化目标是让x逐步趋近于0。
        """
        y = x ** 2 + 20  # 损失函数计算

        # 梯度清零（关键步骤）
        """
        为什么要清零？
        PyTorch的梯度会累积（即每次backward()会把新梯度加到旧梯度上），如果不清零，
        本轮梯度会叠加之前所有轮次的梯度，导致计算错误。因此每次迭代前必须用zero_()重置梯度。
        """
        if x.grad is not None:  # 若梯度已存在（非首轮迭代），则清零
            x.grad.zero_()

        # 2.2- 反向传播计算梯度（求损失函数y对x的偏导数dy/dx）
        """
        反向传播原理：
        - PyTorch会根据计算图自动推导导数，这里y是标量（因x是标量），直接满足backward()对输入为标量的要求。
        - 虽然y.sum()多余（标量求和还是自身），但代码保留了该写法，以符合“标量求导”的规范（通用写法）。
        - 梯度计算结果：根据y = x² + 20，导数dy/dx = 2x（常数20的导数为0）。
          示例：当x=10时，梯度grad = 2*10 = 20；当x=9.8时，grad=2*9.8=19.6，以此类推。
        """
        y.sum().backward()  # 触发反向传播，计算x的梯度（结果存储在x.grad中）

        # 2.3- 梯度下降更新变量x（核心公式：x_new = x_old - lr * grad）
        """
        更新公式解析：
        - x_old：当前轮次的x值
        - lr（学习率）：控制更新步长（此处设为0.01，步长过大会震荡，过小会收敛慢）
        - grad：损失函数对x的梯度（dy/dx=2x），决定更新方向（梯度反方向是损失减小的方向）
        计算示例（首轮）：
        x_old = 10.0，grad = 2*10=20，lr=0.01
        x_new = 10.0 - 0.01*20 = 10.0 - 0.2 = 9.8
        """
        old_x = x.data  # 记录当前x值（用于打印日志）
        lr = 0.01  # 学习率（超参数，控制更新幅度）
        grad = x.grad  # 获取当前梯度（dy/dx=2x）

        # 两种更新方式等价（均只更新x的数值，不影响梯度跟踪）
        x.data = x.data - lr * grad  # 推荐：直接操作data属性，避免修改计算图
        # x.data = x.detach() - lr * grad  # detach()返回无梯度跟踪的张量，效果相同

        # 打印本轮迭代信息（跟踪优化过程）
        print(f"第{epoch + 1}轮次：初始x={old_x:.4f}，梯度={grad:.4f}，更新后x={x.data:.4f}")