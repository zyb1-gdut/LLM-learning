import torch

if __name__ == '__main__':
    # 1- 初始化权重参数w
    """
    权重初始化关键说明：
    - requires_grad=True：标记该张量需要计算梯度（用于反向传播求导），是PyTorch自动微分的核心开关
    - dtype=torch.float32：必须使用浮点类型，因为梯度计算（如W1 = W0 - lr*grad）会产生小数，整数无法存储梯度信息
    - 此处w是二维特征的权重，初始值为[20, 30]，表示两个特征的初始权重分别为20和30
    """
    w = torch.tensor([20, 30], requires_grad=True, dtype=torch.float32)
    print(f"初始权重w：{w}，形状：{w.shape}")  # 输出：tensor([20., 30.], requires_grad=True)


    # 2- 定义损失函数（自定义损失：loss = 2*w²）
    """
    损失函数公式推导：
    - 对于单个权重w_i，损失函数为 loss_i = 2 * w_i²
    - 因w是二维张量[w1, w2]，整体损失张量为 [2*w1², 2*w2²]
    - 代入初始值计算：
      loss1 = 2*(20)² = 2*400 = 800
      loss2 = 2*(30)² = 2*900 = 1800
      故loss张量为 [800., 1800.]
    """
    loss = 2 * w ** 2  # 对w中每个元素分别计算2*平方
    print(f"损失张量loss：{loss}，形状：{loss.shape}")  # 输出：tensor([ 800., 1800.], grad_fn=<MulBackward0>)


    # 3- 反向传播（计算梯度）
    """
    反向传播原理：
    1. 为什么用sum()？backward()要求输入为标量（0维张量），sum()将损失张量[800, 1800]转为标量2600（800+1800）
    2. 梯度计算（链式法则）：
       总损失L = loss1 + loss2 = 2*w1² + 2*w2²
       对w1的梯度：∂L/∂w1 = 4*w1（求导公式：d(2w²)/dw = 4w）
       对w2的梯度：∂L/∂w2 = 4*w2
       代入初始值：
       w1梯度 = 4*20 = 80
       w2梯度 = 4*30 = 120
       故w.grad应为 [80., 120.]
    """
    # 先通过sum()将损失张量转为标量，再调用backward()触发梯度计算
    loss.sum().backward()#把正向传播的路倒着走一遍，沿路用链式法则求微分，最后把结果塞进 .grad 里
    print(f"权重w的梯度（∂L/∂w）：{w.grad}")  # 输出：tensor([ 80., 120.])


    # 4- 更新权重（梯度下降法：W1 = W0 - lr * grad）
    """
    权重更新公式推导：
    - 学习率lr=0.01（控制更新步长，避免更新幅度过大或过小）
    - 新权重计算：
      w1_new = w1_old - lr * ∂L/∂w1 = 20 - 0.01*80 = 20 - 0.8 = 19.2
      w2_new = w2_old - lr * ∂L/∂w2 = 30 - 0.01*120 = 30 - 1.2 = 28.8
    - 使用w.data更新：避免修改张量的计算图（保留梯度跟踪能力，仅更新数值）
    """
    lr = 0.01  # 学习率
    w.data = w.data - lr * w.grad  # 梯度下降更新权重（仅操作数据部分，不影响梯度图）

    # 输出更新后的权重
    """
    结果验证：
    更新后权重应为[19.2, 28.8]，与上述公式计算结果一致，说明梯度下降有效降低了损失（权重向使损失减小的方向调整）
    """
    print("修改后的权重值是：", w.data)  # 输出：tensor([19.2000, 28.8000])