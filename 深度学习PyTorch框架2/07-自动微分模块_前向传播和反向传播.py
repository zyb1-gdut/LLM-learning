import torch

# 设置随机种子为42，确保每次运行时随机初始化的参数（w、b）都相同，保证结果可复现
torch.manual_seed(42)

if __name__ == '__main__':
    # -------------------------- 1. 定义输入特征x --------------------------
    # 输入特征x：形状(2,5)，表示有2个样本，每个样本有5个特征
    # 数学定义：x = [[x₁₁, x₁₂, x₁₃, x₁₄, x₁₅],
    #               [x₂₁, x₂₂, x₂₃, x₂₄, x₂₅]]
    # 此处为了简化计算，所有元素都设为1，即xᵢₖ=1
    x = torch.ones(2, 5)
    print("输入特征x（2个样本，5个特征）：\n", x, "\n形状：", x.shape)

    # -------------------------- 2. 定义真实值y --------------------------
    # 真实值y：形状(2,3)，表示2个样本对应的3个输出维度的真实标签
    # 数学定义：y = [[y₁₁, y₁₂, y₁₃],
    #               [y₂₁, y₂₂, y₂₃]]
    # 此处为了简化计算，所有元素都设为0，即yᵢⱼ=0
    y = torch.zeros(2, 3)
    print("\n真实值y（2个样本，3个输出）：\n", y, "\n形状：", y.shape)

    # -------------------------- 3. 初始化权重w --------------------------
    # 权重w：形状(5,3)，连接5个输入特征到3个输出维度
    # 数学定义：w = [[w₁₁, w₁₂, w₁₃],
    #               [w₂₁, w₂₂, w₂₃],
    #               [w₃₁, w₃₂, w₃₃],
    #               [w₄₁, w₄₂, w₄₃],
    #               [w₅₁, w₅₂, w₅₃]]
    # requires_grad=True：标记为需要计算梯度，用于后续的反向传播
    w = torch.randn(5, 3, requires_grad=True)
    print("\n权重w（5输入→3输出）：\n", w, "\n形状：", w.shape)

    # -------------------------- 4. 初始化偏置b --------------------------
    # 偏置b：形状(3,)，每个输出维度对应一个偏置项
    # 数学定义：b = [b₁, b₂, b₃]
    b = torch.randn(3, requires_grad=True)
    print("\n偏置b（3个输出维度）：\n", b, "\n形状：", b.shape)

    # -------------------------- 5. 计算预测值z（前向传播核心步骤）--------------------------
    # 预测值z：通过线性模型 z = x·w + b 计算得出（矩阵乘法+偏置）
    # 数学公式：zᵢⱼ = Σₖ₌₁⁵(xᵢₖ·wₖⱼ) + bⱼ
    #
    # 具体计算（因为x全为1）：
    # z₁₁ = 1×0.3367 + 1×0.2303 + 1×2.2082 + 1×0.2674 + 1×1.1103 + 0.9580 = 5.1108
    # z₁₂ = 1×0.1288 + 1×(-1.1229) + 1×(-0.6380) + 1×0.5349 + 1×(-1.6898) + 1.3221 = -1.4648
    # z₁₃ = 1×0.2345 + 1×(-0.1863) + 1×0.4617 + 1×0.8094 + 1×(-0.9890) + 0.8172 = 1.1474
    #
    # 由于两个样本的输入x完全相同，所以：
    # z₂₁ = z₁₁ = 5.1108
    # z₂₂ = z₁₂ = -1.4648
    # z₂₃ = z₁₃ = 1.1474
    z = x @ w + b
    print("\n预测值z = x·w + b：\n", z, "\n形状：", z.shape)

    # -------------------------- 6. 定义MSE损失函数 --------------------------
    # MSE（Mean Square Error）损失函数：计算预测值与真实值之间差异的平方的平均值
    # 数学公式：loss = (1/N)·ΣᵢΣⱼ(zᵢⱼ - yᵢⱼ)²
    # 其中N是总的元素个数，这里N = 2×3 = 6
    # 由于y全为0，公式简化为：loss = (1/6)·ΣᵢΣⱼzᵢⱼ²
    loss_fn = torch.nn.MSELoss()

    # -------------------------- 7. 计算损失值 --------------------------
    # 根据实际z值计算损失：
    # loss = (1/6)×[5.1108² + (-1.4648)² + 1.1474² + 5.1108² + (-1.4648)² + 1.1474²]
    #      = (1/6)×[26.1203 + 2.1456 + 1.3165 + 26.1203 + 2.1456 + 1.3165]
    #      = (1/6)×59.1648 ≈ 9.8608
    loss_value = loss_fn(z, y)
    print("\nMSE损失值：", loss_value, "（类型：", type(loss_value), ")")

    # -------------------------- 8. 反向传播计算梯度 --------------------------
    # 核心逻辑：通过链式法则计算loss对w和b的偏导数（梯度）
    #
    # 步骤1：计算loss对z的偏导数（梯度）
    # 根据MSE损失函数：loss = (1/N)·ΣᵢΣⱼ(zᵢⱼ - yᵢⱼ)²
    # 对zᵢⱼ求偏导：∂loss/∂zᵢⱼ = (2/N)·(zᵢⱼ - yᵢⱼ)
    # 由于N=6且yᵢⱼ=0，所以：∂loss/∂zᵢⱼ = (2/6)·zᵢⱼ = zᵢⱼ/3
    # 具体数值：
    # ∂loss/∂z₁₁ = 5.1108/3 ≈ 1.7036
    # ∂loss/∂z₁₂ = -1.4648/3 ≈ -0.4883
    # ∂loss/∂z₁₃ = 1.1474/3 ≈ 0.3825
    # ∂loss/∂z₂₁ = 5.1108/3 ≈ 1.7036
    # ∂loss/∂z₂₂ = -1.4648/3 ≈ -0.4883
    # ∂loss/∂z₂₃ = 1.1474/3 ≈ 0.3825
    #
    # 步骤2：计算z对w和b的偏导数
    # 根据线性模型：zᵢⱼ = Σₖ₌₁⁵(xᵢₖ·wₖⱼ) + bⱼ
    # - z对w的偏导：∂zᵢⱼ/∂wₖⱼ = xᵢₖ
    #   示例：∂z₁₁/∂w₁₁ = x₁₁ = 1，∂z₂₁/∂w₁₁ = x₂₁ = 1
    # - z对b的偏导：∂zᵢⱼ/∂bⱼ = 1
    #
    # 步骤3：使用链式法则求w和b的梯度
    # - w的梯度：∂loss/∂wₖⱼ = Σᵢ(∂loss/∂zᵢⱼ · ∂zᵢⱼ/∂wₖⱼ) = Σᵢ(xᵢₖ · ∂loss/∂zᵢⱼ)
    #   矩阵形式：∇w = (1/3)·xᵀ·z
    # - b的梯度：∂loss/∂bⱼ = Σᵢ(∂loss/∂zᵢⱼ · ∂zᵢⱼ/∂bⱼ) = Σᵢ(∂loss/∂zᵢⱼ)
    #   矩阵形式：∇b = (1/3)·Σzᵢ（按列求和）
    #
    # 具体计算示例：
    # 对于w的第一列梯度：
    # ∂loss/∂w₁₁ = x₁₁·∂loss/∂z₁₁ + x₂₁·∂loss/∂z₂₁ = 1×1.7036 + 1×1.7036 = 3.4072
    # ∂loss/∂w₂₁ = x₁₂·∂loss/∂z₁₁ + x₂₂·∂loss/∂z₂₁ = 1×1.7036 + 1×1.7036 = 3.4072
    # ...其他行也相同，所以w的每行第一列梯度都是3.4072
    #
    # 对于w的第二列梯度：
    # ∂loss/∂w₁₂ = x₁₁·∂loss/∂z₁₂ + x₂₁·∂loss/∂z₂₂ = 1×(-0.4883) + 1×(-0.4883) = -0.9766
    #
    # 对于w的第三列梯度：
    # ∂loss/∂w₁₃ = x₁₁·∂loss/∂z₁₃ + x₂₁·∂loss/∂z₂₃ = 1×0.3825 + 1×0.3825 = 0.7650
    #
    # 对于b的梯度：
    # ∂loss/∂b₁ = ∂loss/∂z₁₁ + ∂loss/∂z₂₁ = 1.7036 + 1.7036 = 3.4072
    # ∂loss/∂b₂ = ∂loss/∂z₁₂ + ∂loss/∂z₂₂ = -0.4883 + (-0.4883) = -0.9766
    # ∂loss/∂b₃ = ∂loss/∂z₁₃ + ∂loss/∂z₂₃ = 0.3825 + 0.3825 = 0.7650

    # 触发反向传播：自动计算所有requires_grad=True参数的梯度
    loss_value.backward()

    # -------------------------- 9. 打印梯度结果 --------------------------
    print("\n权重w的梯度（∇w = ∂loss/∂w）：\n", w.grad)
    print("\n偏置b的梯度（∇b = ∂loss/∂b）：\n", b.grad)

    # -------------------------- 10. 梯度验证计算 --------------------------
    print("\n" + "=" * 50)
    print("梯度验证计算：")

    # 手动计算w的梯度：∇w = (1/3) * xᵀ @ z
    # 因为y=0，所以z-y=z，且N=6，系数为2/6=1/3
    manual_w_grad = (1 / 3) * x.t() @ z
    print("手动计算的w梯度：\n", manual_w_grad)

    # 手动计算b的梯度：∇b = (1/3) * z.sum(dim=0)
    manual_b_grad = (1 / 3) * z.sum(dim=0)
    print("手动计算的b梯度：", manual_b_grad)

    # 验证梯度一致性
    w_grad_error = torch.abs(w.grad - manual_w_grad).max()
    b_grad_error = torch.abs(b.grad - manual_b_grad).max()
    print(f"\n梯度计算误差：")
    print(f"w梯度最大误差：{w_grad_error:.8f}")
    print(f"b梯度最大误差：{b_grad_error:.8f}")

    # 验证损失值计算
    manual_loss = (z * z).sum() / 6  # MSE公式，因为y=0
    print(f"\n损失值验证：")
    print(f"PyTorch计算的loss: {loss_value:.6f}")
    print(f"手动计算的loss: {manual_loss:.6f}")
    print(f"损失值误差: {torch.abs(loss_value - manual_loss):.8f}")